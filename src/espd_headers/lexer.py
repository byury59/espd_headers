"""Лексическая обработка текста C."""
import re


def strip_literals_and_comments(text):
    """
    Заменяет содержимое строковых/символьных литералов и комментариев
    пробелами (сохраняя длину и переносы строк), чтобы последующий поиск
    идентификаторов не находил "переменные" внутри "%s\\n", // текста и т.п.
    """
    pattern = re.compile(
        r'//[^\n]*'              # однострочный комментарий
        r'|/\*.*?\*/'            # блочный комментарий
        r'|"(?:\\.|[^"\\])*"'    # строковый литерал
        r"|'(?:\\.|[^'\\])*'",   # символьный литерал
        re.DOTALL
    )

    def _blank(m):
        return ''.join('\n' if c == '\n' else ' ' for c in m.group(0))
    return pattern.sub(_blank, text)
